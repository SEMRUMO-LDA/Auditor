// Esquema da base de dados (Postgres: Supabase ou o Postgres local embebido).
//
// Duas escolhas para o Postgres se portar como o SQLite que a app usava antes:
//  - Os textos usam a ordenação binária "C", como o SQLite: a ordem das listas e as comparações não dependem da
//    língua do servidor (o Supabase e o Postgres local teriam ordens diferentes).
//  - Os ids são identidades (INTEGER GENERATED ... AS IDENTITY); ao migrar, mantêm-se os ids antigos.
const T = 'TEXT COLLATE "C"';
const ID = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';

export const TABELAS = [
  'users', 'sessions', 'fechos', 'fecho_validacoes', 'resumo_diario', 'movimentos', 'faturas', 'extratos', 'extrato_linhas',
  'extrato_associacoes', 'contagens_numerario', 'caixas', 'meios', 'tpas', 'tpa_caixas', 'envios', 'taloes', 'envio_ficheiros',
  'inconsistencias', 'historico', 'reservas', 'faturas_reserva', 'agencias', 'config', 'login_falhas',
];

export const ESQUEMA = `
CREATE TABLE IF NOT EXISTS users (
  id ${ID},
  username ${T} NOT NULL,
  nome ${T} NOT NULL,
  pass_hash ${T} NOT NULL,
  role ${T} NOT NULL CHECK (role IN ('auditor', 'rececionista')),
  ativo INTEGER NOT NULL DEFAULT 1,
  criado_em ${T} NOT NULL
);
-- O nome de utilizador não distingue maiúsculas de minúsculas (como antes, com COLLATE NOCASE).
CREATE UNIQUE INDEX IF NOT EXISTS users_username_minusculas ON users (lower(username));
CREATE TABLE IF NOT EXISTS sessions (
  token_hash ${T} PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  expira_em ${T} NOT NULL
);

-- Um fecho por dia, com as exportações do PMS.
CREATE TABLE IF NOT EXISTS fechos (
  data ${T} PRIMARY KEY,
  diario_ficheiro ${T}, diario_em ${T}, diario_por INTEGER,
  faturas_ficheiro ${T}, faturas_em ${T}, faturas_por INTEGER,
  total_declarado DOUBLE PRECISION,
  saidas_lista ${T}, saidas_lista_em ${T}, saidas_faturas ${T}, saidas_faturas_em ${T},
  entradas_lista ${T}, entradas_lista_em ${T}, entradas_faturas ${T}, entradas_faturas_em ${T},
  contagem_por INTEGER, contagem_em ${T}
);
-- Valor de cada meio (CASH, TPA, STRIPE...) que o auditor deu como correto no fecho do dia.
-- Guarda o valor validado: se o diário for recarregado e o valor mudar, a validação deixa de contar.
CREATE TABLE IF NOT EXISTS fecho_validacoes (
  data ${T} NOT NULL, meio ${T} NOT NULL, valor_cent BIGINT NOT NULL,
  user_id INTEGER NOT NULL REFERENCES users(id), quando ${T} NOT NULL,
  PRIMARY KEY (data, meio)
);
CREATE TABLE IF NOT EXISTS resumo_diario (
  data ${T} NOT NULL, tipo ${T} NOT NULL, descricao ${T}, valor DOUBLE PRECISION NOT NULL,
  PRIMARY KEY (data, tipo)
);
CREATE TABLE IF NOT EXISTS movimentos (
  id ${ID},
  data ${T} NOT NULL, utilizador ${T}, secao ${T}, tipo ${T}, tipo_desc ${T}, hora ${T},
  doc ${T}, obs ${T}, quarto ${T}, nome ${T}, valor DOUBLE PRECISION NOT NULL, caixa ${T}, motivo ${T},
  total_utilizador DOUBLE PRECISION, doc_data ${T}
);
CREATE INDEX IF NOT EXISTS movimentos_data ON movimentos(data);
CREATE TABLE IF NOT EXISTS faturas (
  id ${ID},
  data ${T} NOT NULL, hotel ${T}, reserva ${T}, quarto ${T}, hospede ${T},
  checkin ${T}, checkout ${T}, total_reserva DOUBLE PRECISION, doc ${T}, valor DOUBLE PRECISION NOT NULL, tipo ${T}, info ${T}
);
CREATE INDEX IF NOT EXISTS faturas_data ON faturas(data);

-- Extratos bancários e relatórios de pagamentos (Booking.com, Stripe): o comprovativo das transferências.
CREATE TABLE IF NOT EXISTS extratos (
  id ${ID},
  tipo ${T} NOT NULL CHECK (tipo IN ('banco', 'stripe', 'booking')),
  nome_original ${T} NOT NULL,
  criado_em ${T} NOT NULL,
  user_id INTEGER REFERENCES users(id),
  de ${T}, ate ${T}, colunas ${T}
);
CREATE TABLE IF NOT EXISTS extrato_linhas (
  id ${ID},
  extrato_id INTEGER NOT NULL REFERENCES extratos(id) ON DELETE CASCADE,
  n INTEGER,
  data ${T} NOT NULL,
  descricao ${T}, valor DOUBLE PRECISION NOT NULL, saldo DOUBLE PRECISION,
  categoria ${T} NOT NULL,           -- banco: transferencia | booking | stripe | saida; relatórios: detalhe | payout | outro
  referencia ${T}, hospede ${T}, checkin ${T}, checkout ${T},
  grupo ${T}, grupo_data ${T}, liquido DOUBLE PRECISION, taxa DOUBLE PRECISION, convertido DOUBLE PRECISION,
  chave ${T}
);
CREATE INDEX IF NOT EXISTS extrato_linhas_cat ON extrato_linhas(categoria, data);
CREATE INDEX IF NOT EXISTS extrato_linhas_ext ON extrato_linhas(extrato_id);
-- Associações feitas à mão pelo auditor entre um movimento do diário e uma linha de extrato.
CREATE TABLE IF NOT EXISTS extrato_associacoes (
  id ${ID},
  data ${T} NOT NULL, doc ${T} NOT NULL, valor_cent BIGINT NOT NULL,
  linha_id INTEGER NOT NULL REFERENCES extrato_linhas(id) ON DELETE CASCADE,
  criado_em ${T}, user_id INTEGER,
  UNIQUE (data, doc, valor_cent)
);

-- Contagem de notas e moedas feita pelo auditor, por dia (valor da denominação em cêntimos).
CREATE TABLE IF NOT EXISTS contagens_numerario (
  data ${T} NOT NULL, valor INTEGER NOT NULL, quantidade INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (data, valor)
);

-- Configuração.
CREATE TABLE IF NOT EXISTS caixas (codigo ${T} PRIMARY KEY);
CREATE TABLE IF NOT EXISTS meios (codigo ${T} PRIMARY KEY, descricao ${T}, tpa INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS tpas (id ${ID}, numero ${T} NOT NULL UNIQUE, nome ${T});
-- Um TPA pode servir várias unidades (caixas) e uma unidade pode ter vários TPA.
CREATE TABLE IF NOT EXISTS tpa_caixas (
  tpa_id INTEGER NOT NULL REFERENCES tpas(id) ON DELETE CASCADE,
  caixa ${T} NOT NULL,
  PRIMARY KEY (tpa_id, caixa)
);

-- Um envio é uma fotografia (ou PDF); pode conter vários talões.
CREATE TABLE IF NOT EXISTS envios (
  id ${ID},
  user_id INTEGER NOT NULL REFERENCES users(id),
  ficheiro ${T} NOT NULL, mime ${T} NOT NULL, nome_original ${T},
  criado_em ${T} NOT NULL,
  estado ${T} NOT NULL DEFAULT 'rascunho' CHECK (estado IN ('rascunho', 'confirmado')),
  confirmado_em ${T}, confirmado_por INTEGER,
  leitura_json ${T}, leitura_erro ${T},
  nota ${T}
);
-- Bases de dados criadas antes de existirem as notas dos utilizadores:
ALTER TABLE envios ADD COLUMN IF NOT EXISTS nota ${T};
CREATE TABLE IF NOT EXISTS taloes (
  id ${ID},
  envio_id INTEGER NOT NULL REFERENCES envios(id) ON DELETE CASCADE,
  tipo ${T} NOT NULL CHECK (tipo IN ('compra', 'fecho')),
  tpa ${T}, data ${T}, hora ${T}, valor DOUBLE PRECISION, cartao ${T}, ultimos4 ${T},
  reservas ${T} NOT NULL DEFAULT '',
  reserva_lida ${T} NOT NULL DEFAULT '',
  reserva_origem ${T} NOT NULL DEFAULT '',
  duvidoso INTEGER NOT NULL DEFAULT 0,
  doc_associado ${T}
);
CREATE INDEX IF NOT EXISTS taloes_data ON taloes(data);
-- O conteúdo da fotografia ou PDF de cada envio fica na base de dados: numa função sem disco persistente (Vercel)
-- não há onde guardar ficheiros.
CREATE TABLE IF NOT EXISTS envio_ficheiros (
  envio_id INTEGER PRIMARY KEY REFERENCES envios(id) ON DELETE CASCADE,
  conteudo BYTEA NOT NULL
);

CREATE TABLE IF NOT EXISTS inconsistencias (
  id ${ID},
  data ${T} NOT NULL, tipo ${T} NOT NULL, chave ${T} NOT NULL,
  gravidade ${T} NOT NULL, titulo ${T} NOT NULL, detalhe_json ${T} NOT NULL,
  utilizador ${T}, caixa ${T}, valor DOUBLE PRECISION,
  estado ${T} NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente', 'justificada', 'resolvida')),
  ativa INTEGER NOT NULL DEFAULT 1,
  criada_em ${T} NOT NULL, atualizada_em ${T} NOT NULL,
  UNIQUE (data, tipo, chave)
);
-- Notas e mudanças de estado: só se acrescenta, nunca se altera nem apaga.
CREATE TABLE IF NOT EXISTS historico (
  id ${ID},
  inconsistencia_id INTEGER NOT NULL REFERENCES inconsistencias(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id),
  quando ${T} NOT NULL,
  kind ${T} NOT NULL CHECK (kind IN ('nota', 'estado')),
  texto ${T}, estado_de ${T}, estado_para ${T}
);

-- Listas de saídas e de entradas do dia (uma linha por quarto) e todas as faturas dessas reservas.
CREATE TABLE IF NOT EXISTS reservas (
  id ${ID},
  data ${T} NOT NULL, lado ${T} NOT NULL CHECK (lado IN ('saida', 'entrada')),
  reserva ${T} NOT NULL, unidade ${T}, hospede ${T}, checkin ${T}, checkout ${T}, status ${T},
  pax INTEGER, total DOUBLE PRECISION, agencia ${T}, mercado ${T}, canal ${T}, info ${T}, criada_por ${T}
);
CREATE INDEX IF NOT EXISTS reservas_data ON reservas(data, lado);
CREATE TABLE IF NOT EXISTS faturas_reserva (
  id ${ID},
  data ${T} NOT NULL, lado ${T} NOT NULL,
  reserva ${T} NOT NULL, quarto ${T}, doc ${T}, doc_data ${T}, valor DOUBLE PRECISION NOT NULL, tipo ${T}
);
CREATE INDEX IF NOT EXISTS faturas_reserva_data ON faturas_reserva(data, lado);
-- Como se espera que cada agência seja faturada: 'imediata' (até à estadia), 'prazo' (dias depois da saída)
-- ou 'agencia' (faturada à parte, fora deste relatório).
CREATE TABLE IF NOT EXISTS agencias (nome ${T} PRIMARY KEY, regra ${T} NOT NULL CHECK (regra IN ('imediata', 'prazo', 'agencia')));
CREATE TABLE IF NOT EXISTS config (chave ${T} PRIMARY KEY, valor ${T} NOT NULL);
-- Tentativas de login falhadas (por utilizador e endereço), para limitar as repetições. Na base de dados e não em
-- memória, porque numa função sem estado cada pedido pode correr numa instância diferente.
CREATE TABLE IF NOT EXISTS login_falhas (chave ${T} PRIMARY KEY, n INTEGER NOT NULL, ultima BIGINT NOT NULL);
`;

// No Supabase, as tabelas do esquema "public" ficam acessíveis a quem tiver a chave pública (anon) através da API de
// dados. A app liga-se diretamente ao Postgres (o papel "postgres" ignora o RLS), por isso o RLS ligado e sem
// políticas fecha essa porta: ninguém lê nem escreve nada pela API. É idempotente.
export const SEGURANCA = TABELAS.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n');
